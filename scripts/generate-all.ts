import { readFileSync, writeFileSync } from 'node:fs';
import type { DictionaryData } from '../src/dictionary/model.ts';
import { FIXT11 } from '../src/version.ts';
import { parseOrchestra } from './orchestra.ts';
import { checkCorrectionsApply, correct } from './corrections.ts';
import { composeDictionary, generateData, generateJson, generateTypes, sessionLayerAlone } from './generate.ts';

const read = (file: string): DictionaryData => correct(parseOrchestra(readFileSync(`dictionaries/orchestra/${file}`, 'utf8')));
const report = (name: string, data: DictionaryData): void =>
  console.log(`${name}: ${data.fields.length} fields, ${data.messages.length} messages, ${data.groups.length} groups`);

// Every file is read first: a correction that fits none of them stops the generator before any file is written.
// FIX 4.2 and FIX 4.4 have one file each, session layer and application layer together.
const single = [
  { file: 'OrchestraFIX42.xml', name: 'fix42' },
  { file: 'OrchestraFIX44.xml', name: 'fix44' },
].map(entry => ({ ...entry, data: read(entry.file) }));

// FIXT.1.1: the session layer on its own, and with the application layer it carries (FIX Latest,
// which is FIX 5.0 SP2 and every extension pack since). The second is large, so its tables are
// JSON, read when first needed. On its own the session layer still names every message type, for
// the ones a Logon lists (RefMsgType).
const session = 'dictionaries/orchestra/FIXTSession.xml';
const application = 'dictionaries/orchestra/OrchestraFIXLatest.xml';
const sessionFile = read('FIXTSession.xml');
const applicationFile = read('OrchestraFIXLatest.xml');
checkCorrectionsApply([...single.map(({ data }) => data.version), sessionFile.version, applicationFile.version]);

for (const { file, name, data } of single) {
  const banner = `// Generated by scripts/generate-all.ts from dictionaries/orchestra/${file}. Do not edit.\n`;
  writeFileSync(`src/dictionary/${name}.data.ts`, banner + generateData(data));
  writeFileSync(`src/dictionary/${name}.ts`, banner + generateTypes(data));
  report(name, data);
}

const layer: DictionaryData = { ...sessionFile, version: FIXT11 };
const fix50sp2 = composeDictionary(layer, applicationFile);
const fixt11 = sessionLayerAlone(layer, fix50sp2);
writeFileSync('src/dictionary/fixt11.data.ts',
  `// Generated by scripts/generate-all.ts from ${session}, with the message types of ${application}. Do not edit.\n` + generateData(fixt11));
writeFileSync('src/dictionary/fix50sp2.data.json', generateJson(fix50sp2));
writeFileSync('src/dictionary/fix50sp2.ts',
  `// Generated by scripts/generate-all.ts from ${session} and ${application}. Do not edit.\n` + generateTypes(fix50sp2));
report('fixt11', fixt11);
report('fix50sp2', fix50sp2);
